"""
tools/test_infrastructure.py
============================================================
Persistent self-test suite for the S3 infrastructure.

Run:  python tools/test_infrastructure.py
(R interpreter resolved via env var RSCRIPT, default "Rscript"
 — per SPEC v2 §4.4)

Every test documents WHAT IT FALSIFIES (S3 mandatory fix 2):
a passing suite must rule out specific regressions, not merely
show that two implementations agree with each other.

Tests
-----
T1  volatile-exclusion, per implementation, per table that HAS
    volatile columns (P2/R1/R2/R3/R6): two CSVs identical except
    for volatile-column values must produce IDENTICAL fingerprints.
    Falsifies: volatile columns leaking into md5/statistics (the
    exact bug of the first S3 delivery; running it PER
    IMPLEMENTATION means a symmetric bug on both sides cannot
    hide behind cross-language agreement).
T2  non-volatile sensitivity: changing a NON-volatile numeric
    column must change the fingerprint.
    Falsifies: exclusion being too broad (e.g. comparing nothing).
T3  cross-language agreement: same CSV fingerprinted by Python and
    R must yield identical JSON.
    Falsifies: serialization drift between the two implementations.
T4  constants-drift lock: fingerprint.R --dump-constants must equal
    tools/qc_schema.py for CANONICAL_COLUMNS, VOLATILE_COLUMNS,
    SHARD_TO_TABLE, EXCLUDED_FILES.
    Falsifies: silent desync of the hand-mirrored R constants.
T5  excluded-set audit (Q5(b)): fingerprint "excluded" equals the
    declared volatile list and "colnames" still contains them.
    Falsifies: the exclusion set shrinking/expanding unnoticed.
T6  schema-drift refusal: a table that declares a volatile column
    the CSV lacks must REFUSE to fingerprint (both implementations).
    Falsifies: silent acceptance of a drifted column layout.
    (S3 补3: the refusal is asserted on the specific message, not just
    on a non-zero exit / ValueError type.)
T7  all-NA declared-numeric column: an all-NA column that the schema
    declares numeric must be fingerprinted as "numeric" on BOTH sides.
    Falsifies: reader-inference divergence (pandas float64 vs fread
    logical) splitting one column across numeric/text and breaking
    cross-language equality. (补2a)
T8  partial-NA + tricky values: a partially-NA numeric column and
    non-exactly-representable doubles must agree cross-language.
    Falsifies: %.10f rounding divergence or NA-dependent aggregate
    min/max/sum differences. (补2b/c)
T9  .rds fingerprint: two Seurat objects built by the same code run
    twice (so @commands$time.stamp DIFFERS) must fingerprint identically;
    mutating one meta.data column must change it.
    Falsifies: @commands timestamp leaking into the fingerprint, or
    over-exclusion hiding a real content change. (补1)
T10 .h5 fingerprint: two h5 files generated by the same fixture code
    must fingerprint identically, for both matrix and unknown layouts.
    Falsifies: h5 fingerprint depending on HDF5 internal ordering or
    layout-specific fields. (补1)
T11 fixture-dir type coverage: fingerprint a fixture directory whose
    CSVs are NOT in CANONICAL_COLUMNS; assert numeric columns land in
    "numeric".  Input is independent of qc_schema (make_fixture output),
    so it catches regressions invisible to T1-T10 whose inputs all
    derive from sample_rows()/CANONICAL_COLUMNS.
    Falsifies: content-based typing leaving scientific CSVs' numeric
    columns (rho/p/q/coords/densities) as 'text'. (补2 regression fix)
============================================================
"""

