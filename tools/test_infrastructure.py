# Non-exactly-representable binary doubles that exercise the 10th-
# decimal rounding of %.10f on both sides (补2c).  These force the
# two implementations to agree on the same fortran-97 rounding, not
# merely on values that happen to be exact.
TRICKY_VALUES = [
    0.12345678901234,
    -1e-11,
    1e8 + 0.05,
    0.1,
    2.0 / 3.0,
    -123.45678901234,
]


def sample_rows(table, na_columns=()):
    """Two plausible rows covering all canonical columns of a table.

    Numeric stand-ins are drawn from TRICKY_VALUES (alternating) so
    cross-language %.10f agreement is actually exercised.  Columns in
    na_columns are set to NA in BOTH rows (for all-NA and partial-NA
    cases, 补2a/b).
    """
    cols = qc_schema.CANONICAL_COLUMNS[table]
    key = "sample_name" if "sample_name" in cols else "sample"
    rows = []
    for i, sname in enumerate(("Beta_Set/S2", "Alpha_Set/S1")):
        row = {}
        for j, c in enumerate(cols):
            if c in na_columns:
                row[c] = np.nan
            elif c == key:
                row[c] = sname
            elif c in ("dataset",):
                row[c] = sname.split("/")[0]
            elif c in ("species", "condition", "preservation",
                       "data_quality_tier", "h5_path_type",
                       "top1_gene", "top1_tier1_gene"):
                row[c] = f"v{j}"
            else:
                # non-exactly-representable numeric stand-in
                row[c] = TRICKY_VALUES[(i + j) % len(TRICKY_VALUES)]
        rows.append(row)
    return cols, key, rows


def write_table_csv(tmp, table, volatile_overrides=None, suffix="",
                    na_columns=()):
    """Write a 2-row CSV named EXACTLY as the canonical table basename
    (fingerprint resolution is by basename), inside its own subdir.
    volatile_overrides maps column -> [row0_value, row1_value].
    na_columns: columns set to NA in both rows (补2a/b)."""
    cols, key, rows = sample_rows(table, na_columns=na_columns)
    vol = qc_schema.VOLATILE_COLUMNS[table]
    for c in vol:
        if c in na_columns:
            continue
        base = volatile_overrides.get(c, [11.1, 22.2]) if volatile_overrides \
            else [11.1, 22.2]
        rows[0][c] = base[0]
        rows[1][c] = base[1]
    d = tempfile.mkdtemp(dir=tmp, prefix=table + suffix + "_")
    path = os.path.join(d, table)
    import csv
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=cols)
        w.writeheader()
        w.writerows(rows)
    return path


def fp_r(path, extra_args=None):
    cmd = [RSCRIPT, FP_R, "--file", path] + (extra_args or [])
    p = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8")
    if p.returncode != 0:
        raise RuntimeError(f"R fingerprint failed: {p.stderr[-500:]}")
    return json.loads(p.stdout)


def equal_json(a, b):
    return json.dumps(a, sort_keys=True) == json.dumps(b, sort_keys=True)


