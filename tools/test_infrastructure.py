def _make_pipeline_fixture(tmp, sample="Fixture_Human/Donor1"):
    """Generate a minimal fixture and run P1b+P2b in flat mode to
    produce a Nextflow-work-dir-style flat layout for one sample."""
    root = os.path.dirname(HERE)  # project root (parent of tools/)
    fdir = os.path.join(tmp, "fixture")
    p = subprocess.run([sys.executable, os.path.join(root, "tools", "make_fixture.py"),
                        "--outdir", fdir], capture_output=True, text=True, encoding="utf-8",
                       cwd=root)
    if p.returncode != 0:
        print(f"       make_fixture FAILED (rc={p.returncode}): {p.stderr[-200:]}")
        return None, None
    reg = os.path.join(fdir, "sample_registry.json")
    work = os.path.join(tmp, "work")
    os.makedirs(work, exist_ok=True)
    # P1b flat
    p = subprocess.run([sys.executable, os.path.join(root, "01_python_preprocessing", "P1b_data_loading.py"),
                        "--registry", reg, "--sample", sample,
                        "--outdir", work], capture_output=True, text=True, encoding="utf-8",
                       cwd=root)
    if p.returncode != 0:
        print(f"       P1b flat FAILED: {p.stderr[-200:]}")
        return None, None
    # P2a for the dataset — manifest must cover ALL samples in the
    # dataset (P2a validates completeness), so generate P1b flat for
    # every sibling sample too
    ds = sample.split("/")[0]
    sub = sample.split("/")[1]
    import json as _json
    with open(reg, "r") as _fh:
        _reg = _json.load(_fh)
    sibling_samples = [s for s in _reg if s.split("/")[0] == ds]
    ml = os.path.join(tmp, "ml.txt")
    with open(ml, "w", encoding="utf-8") as fh:
        for sib in sibling_samples:
            sib_work = os.path.join(tmp, "work_" + sib.replace("/", "_"))
            os.makedirs(sib_work, exist_ok=True)
            p = subprocess.run([sys.executable, os.path.join(root, "01_python_preprocessing", "P1b_data_loading.py"),
                                "--registry", reg, "--sample", sib,
                                "--outdir", sib_work],
                               capture_output=True, text=True, encoding="utf-8", cwd=root)
            if p.returncode != 0:
                print(f"       P1b flat for {sib} FAILED: {p.stderr[-200:]}")
                return None, None
            fh.write(sib + "\t" + os.path.join(sib_work, "cell_metadata.csv") + "\n")
    p2a_out = os.path.join(tmp, "p2a")
    p = subprocess.run([sys.executable, os.path.join(root, "01_python_preprocessing", "P2a_select_k.py"),
                        "--dataset", ds, "--registry", reg,
                        "--metadata-list", ml, "--outdir", p2a_out],
                       capture_output=True, text=True, encoding="utf-8", cwd=root)
    if p.returncode != 0:
        print(f"       P2a FAILED: {p.stderr[-200:]}")
        return None, None
    # P2b flat into same work dir
    p = subprocess.run([sys.executable, os.path.join(root, "01_python_preprocessing", "P2b_density.py"),
                        "--sample", sample, "--registry", reg,
                        "--kfile", os.path.join(p2a_out, "k_selection.json"),
                        "--metadata", os.path.join(work, "cell_metadata.csv"),
                        "--outdir", work], capture_output=True, text=True, encoding="utf-8",
                       cwd=root)
    if p.returncode != 0:
        print(f"       P2b FAILED: {p.stderr[-200:]}")
        return None, None
    return work, reg


