def t13_manifest_order_invariance(tmp):
    """P2a --metadata-list with shuffled row order must produce the
    SAME all_samples_knn_cv.csv fingerprint as ordered rows.

    k_selection.json is the WRONG thing to compare here: mean_cv is
    row-order-invariant (axis=0 mean), K comes from argmax, dist_* is
    rounded — positional pairing barely moves it.  The ACTUAL victim
    of positional pairing is all_samples_knn_cv.csv: its column names
    are sample names taken from the manifest, but the data columns are
    cv_list values positional-paired to sample_list; a shuffle swaps
    which sample's CV lands under which sample's name.  This test
    catches that.

    Falsifies: positional pairing (必修B) — Nextflow task completion
    order is not guaranteed; positional pairing would swap CV vectors
    across samples, mislabeling all_samples_knn_cv.csv columns and
    diagnostic plot legends.

    Reverse-verification: confirmed FAIL on the pre-fix (positional)
    version — see T13_REV in the report."""
    import json
    d = tempfile.mkdtemp(dir=tmp, prefix="t13_")
    # two cell_metadata.csv files with DISTINCT coordinate distributions
    # so their CV vectors differ (making column-name swap detectable)
    for idx, sname in enumerate(("TestDS/S1", "TestDS/S2")):
        sd = os.path.join(d, sname.replace("/", "_"))
        os.makedirs(sd)
        # fixed integer seed (NOT hash(sname) — Python string hash is
        # randomized per process, making the fixture non-reproducible)
        rng = np.random.default_rng(100 + idx)
        pd.DataFrame({
            "cell_id": [f"c{i}" for i in range(60)],
            "x_centroid": rng.uniform(0, 1000, 60).round(3),
            "y_centroid": rng.uniform(0, 1000, 60).round(3),
        }).to_csv(os.path.join(sd, "cell_metadata.csv"), index=False)
    reg = {"TestDS/S1": {"species": "human"},
           "TestDS/S2": {"species": "human"}}
    reg_path = os.path.join(d, "registry.json")
    with open(reg_path, "w") as fh:
        json.dump(reg, fh)
    s1_meta = os.path.join(d, "TestDS_S1", "cell_metadata.csv")
    s2_meta = os.path.join(d, "TestDS_S2", "cell_metadata.csv")
    # ordered manifest
    man_ordered = os.path.join(d, "ordered.txt")
    with open(man_ordered, "w", encoding="utf-8") as fh:
        fh.write(f"TestDS/S1\t{s1_meta}\n")
        fh.write(f"TestDS/S2\t{s2_meta}\n")
    # shuffled manifest (rows reversed)
    man_shuffled = os.path.join(d, "shuffled.txt")
    with open(man_shuffled, "w", encoding="utf-8") as fh:
        fh.write(f"TestDS/S2\t{s2_meta}\n")
        fh.write(f"TestDS/S1\t{s1_meta}\n")
    out_ordered = os.path.join(d, "ordered")
    out_shuffled = os.path.join(d, "shuffled")
    for man, outd in [(man_ordered, out_ordered), (man_shuffled, out_shuffled)]:
        p = subprocess.run([sys.executable,
                            "01_python_preprocessing/P2a_select_k.py",
                            "--dataset", "TestDS",
                            "--registry", reg_path,
                            "--metadata-list", man,
                            "--outdir", outd],
                           capture_output=True, text=True, encoding="utf-8")
        if p.returncode != 0:
            record("T13 manifest order invariance (all_samples_knn_cv.csv)", False,
                   f"P2a failed: {p.stderr[-300:]}")
            return
    # compare all_samples_knn_cv.csv fingerprints (the column-name/data
    # pairing is what positional bugs corrupt — NOT k_selection.json)
    fp_ordered = fppy.fingerprint_file(os.path.join(out_ordered, "all_samples_knn_cv.csv"))
    fp_shuffled = fppy.fingerprint_file(os.path.join(out_shuffled, "all_samples_knn_cv.csv"))
    ok = equal_json(fp_ordered, fp_shuffled)
    if not ok:
        print(f"       ordered colnames: {fp_ordered.get('colnames')}")
        print(f"       shuffled colnames: {fp_shuffled.get('colnames')}")
    record("T13 manifest order invariance (all_samples_knn_cv.csv fingerprint)",
           ok,
           "positional pairing in --metadata-list (必修B): shuffled manifest "
           "rows swap CV vectors across samples, mislabeling "
           "all_samples_knn_cv.csv columns — k_selection.json is NOT "
           "affected (mean_cv is row-order-invariant), so comparing "
           "k_selection.json would false-pass")


