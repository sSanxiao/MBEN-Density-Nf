def t1_volatile_exclusion(tmp):
    """Same table, only volatile columns differ -> identical fingerprint.
    Run for BOTH implementations across all 5 tables that carry volatile
    columns."""
    tables = [t for t in qc_schema.CANONICAL_COLUMNS
              if qc_schema.VOLATILE_COLUMNS[t]]
    all_ok = True
    detail = []
    for table in tables:
        p_a = write_table_csv(tmp, table,
                              {c: [11.1, 22.2] for c in qc_schema.VOLATILE_COLUMNS[table]},
                              suffix="_a")
        p_b = write_table_csv(tmp, table,
                              {c: [999.9, 888.8] for c in qc_schema.VOLATILE_COLUMNS[table]},
                              suffix="_b")

        py_a, py_b = fppy.fingerprint_csv(p_a), fppy.fingerprint_csv(p_b)
        r_a, r_b = fp_r(p_a), fp_r(p_b)

        ok_py = equal_json(py_a, py_b)
        ok_r = equal_json(r_a, r_b)
        detail.append(f"{table}: py={'same' if ok_py else 'DIFF'}, "
                      f"r={'same' if ok_r else 'DIFF'}")
        all_ok &= ok_py and ok_r
    print("       " + "; ".join(detail))
    record("T1 volatile-exclusion (per implementation, 5 tables)", all_ok,
           "volatile columns (time_seconds/rds_size_mb/time_*_s) leaking "
           "into md5/statistics; symmetric bugs cannot hide because each "
           "implementation is checked against itself")


def t2_nonvolatile_sensitivity(tmp):
    """Changing a NON-volatile numeric column must change the fingerprint."""
    table = "ALL_SAMPLES_R2_QC.csv"  # has volatile + stable columns
    p_a = write_table_csv(tmp, table, suffix="_sensa")
    cols, key, rows = sample_rows(table)
    for c in qc_schema.VOLATILE_COLUMNS[table]:
        rows[0][c] = 11.1
        rows[1][c] = 22.2
    rows[0]["n_clusters"] = 77  # non-volatile change
    d = tempfile.mkdtemp(dir=tmp, prefix=table + "_sensb_")
    p_b = os.path.join(d, table)
    import csv
    with open(p_b, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=cols)
        w.writeheader()
        w.writerows(rows)

    py_diff = not equal_json(fppy.fingerprint_csv(p_a), fppy.fingerprint_csv(p_b))
    r_diff = not equal_json(fp_r(p_a), fp_r(p_b))
    record("T2 non-volatile sensitivity", py_diff and r_diff,
           "over-broad exclusion that stops comparing real content "
           "(fingerprint of everything would then trivially match)")


def t3_cross_language(tmp):
    """Same CSV -> Python and R fingerprints identical."""
    table = "ALL_SAMPLES_R2_QC.csv"
    p = write_table_csv(tmp, table, suffix="_xlang")
    py = fppy.fingerprint_csv(p)
    r = fp_r(p)
    ok = equal_json(py, r)
    if not ok:
        for k in py:
            if json.dumps(py.get(k), sort_keys=True) != json.dumps(r.get(k), sort_keys=True):
                print(f"       first differing field: {k}")
                break
    record("T3 cross-language agreement (incl. volatile tables)", ok,
           "serialization drift between the two implementations "
           "(%.10f formatting, NA handling, sort order, key construction)")


def t4_constants_drift(tmp):
    """fingerprint.R --dump-constants must equal qc_schema.py."""
    p = subprocess.run([RSCRIPT, FP_R, "--dump-constants"],
                       capture_output=True, text=True, encoding="utf-8")
    if p.returncode != 0:
        record("T4 constants-drift lock", False,
               f"dump failed: {p.stderr[-300:]}")
        return
    r = json.loads(p.stdout)
    py = {
        "CANONICAL_COLUMNS": {k: list(v) for k, v in
                              qc_schema.CANONICAL_COLUMNS.items()},
        "VOLATILE_COLUMNS": {k: list(v) for k, v in
                             qc_schema.VOLATILE_COLUMNS.items()},
        "NUMERIC_COLUMNS": {k: list(v) for k, v in
                            qc_schema.NUMERIC_COLUMNS.items()},
        "K_SELECTION_COLUMNS": list(qc_schema.K_SELECTION_COLUMNS),
        "SHARD_TO_TABLE": dict(qc_schema.SHARD_TO_TABLE),
        "EXCLUDED_FILES": list(qc_schema.EXCLUDED_FILES),
    }
    ok = True
    for section in py:
        if json.dumps(py[section], sort_keys=True) != \
                json.dumps(r.get(section), sort_keys=True):
            print(f"       drift in section: {section}")
            ok = False
    record("T4 constants-drift lock (R mirror vs qc_schema.py)", ok,
           "silent desync of the hand-mirrored R constants "
           "(would make the two fingerprinters diverge without any error)")


def t5_excluded_audit(tmp):
    """Fingerprint must record excluded == declared volatile list and
    keep volatile names inside colnames (Q5(b))."""
    table = "ALL_SAMPLES_R2_QC.csv"
    p = write_table_csv(tmp, table, suffix="_audit")
    vol = qc_schema.VOLATILE_COLUMNS[table]
    py = fppy.fingerprint_csv(p)
    r = fp_r(p)
    ok = (py["excluded"] == vol and r["excluded"] == vol
          and all(c in py["colnames"] for c in vol)
          and all(c in r["colnames"] for c in vol))
    record("T5 excluded-set audit (Q5b)", ok,
           "the exclusion set shrinking/expanding unnoticed, or excluded "
           "columns vanishing from colnames (both must stay auditable)")


def t7_allna_type_agreement(tmp):
    """An all-NA DECLARED-numeric column must be fingerprinted as
    "numeric" on BOTH sides (补2a).

    Real scenario: a numeric column that is NA for every sample (e.g.
    median_cell_area when no sample has cell_area).  pandas would infer
    such a column as float64, fread as logical — a structural split
    between the two JSONs.  The schema declaration must override both
    readers, so both sides emit "numeric" with NA min/max/sum.
    """
    table = "ALL_SAMPLES_R1_QC.csv"  # has declared-numeric median_cell_area
    p = write_table_csv(tmp, table, suffix="_allna",
                        na_columns=["median_cell_area"])
    py = fppy.fingerprint_csv(p)
    r = fp_r(p)

    ok = (
        "median_cell_area" in py["numeric"]
        and "median_cell_area" in r["numeric"]
        and py["numeric"]["median_cell_area"]["min"] == "NA"
        and r["numeric"]["median_cell_area"]["min"] == "NA"
        and equal_json(py, r)
    )
    if not ok:
        print("       py numeric keys:", list(py["numeric"].keys()))
        print("       r  numeric keys:", list(r["numeric"].keys()))
    record("T7 all-NA declared-numeric column -> 'numeric' on both sides",
           ok,
           "reader-inference divergence for all-NA columns (pandas "
           "float64 vs fread logical would split one column across "
           "'numeric' and 'text', breaking cross-language equality)")

def t8_partial_na_and_precision(tmp):
    """Partial-NA columns and non-exactly-representable values must
    round-trip identically on both sides (补2b/c)."""
    table = "ALL_SAMPLES_R2_QC.csv"
    # partially NA numeric column (one row NA, one row a tricky value)
    cols, key, rows = sample_rows(table, na_columns=["residual_mean"])
    rows[1]["residual_mean"] = 0.12345678901234  # row1 gets a value again
    for c in qc_schema.VOLATILE_COLUMNS[table]:
        rows[0][c] = 11.1
        rows[1][c] = 22.2
    d = tempfile.mkdtemp(dir=tmp, prefix=table + "_partna_")
    p = os.path.join(d, table)
    import csv
    with open(p, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=cols)
        w.writeheader()
        w.writerows(rows)

    py = fppy.fingerprint_csv(p)
    r = fp_r(p)
    ok = equal_json(py, r)
    if not ok:
        for k in ("numeric", "text"):
            if json.dumps(py.get(k), sort_keys=True) != \
                    json.dumps(r.get(k), sort_keys=True):
                print(f"       differing section: {k}")
                break
    record("T8 partial-NA + tricky %.10f values agree cross-language",
           ok,
           "%.10f rounding divergence on non-exactly-representable "
           "doubles, or different min/max/sum when a column is partially "
           "NA (NA handling in aggregate statistics)")


def t6_schema_drift_refusal(tmp):
    """A declared-but-absent volatile column must REFUSE fingerprinting,
    and the refusal must be the SPECIFIC reason (not any failure)."""
    table = "ALL_SAMPLES_R2_QC.csv"
    cols, key, rows = sample_rows(table)
    for c in qc_schema.VOLATILE_COLUMNS[table]:
        rows[0][c] = 11.1
        rows[1][c] = 22.2
    cols_missing = [c for c in cols if c != "time_seconds"]  # drop a volatile col
    d = tempfile.mkdtemp(dir=tmp, prefix=table + "_drift_")
    p = os.path.join(d, table)
    import csv
    with open(p, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=cols_missing)
        w.writeheader()
        w.writerows([{k: v for k, v in row.items() if k in cols_missing}
                     for row in rows])

    # Python side: the exception must be the SPECIFIC drift message.
    py_refused = False
    try:
        fppy.fingerprint_csv(p)
    except ValueError as e:
        py_refused = "refusing to fingerprint" in str(e)

    # R side: stderr must contain the specific refusal phrase, not merely
    # a non-zero exit (which any failure — missing package, bad path —
    # would also produce).
    proc = subprocess.run([RSCRIPT, FP_R, "--file", p],
                          capture_output=True, text=True, encoding="utf-8")
    r_refused = "refusing to fingerprint" in proc.stderr
    record("T6 schema-drift refusal (both implementations, message-checked)",
           py_refused and r_refused,
           "silent acceptance of a drifted column layout, OR a false "
           "'pass' produced by an unrelated failure (missing package / "
           "bad path) that only happens to exit non-zero")


# R helper that builds a small Seurat object and writes it to --out.
# @commands$time.stamp differs between two independent runs, so two
# such objects let us prove the .rds fingerprint STABLE over timestamps.
RDS_MAKER_R = r'''
suppressPackageStartupMessages({ library(Seurat); library(Matrix) })
args <- commandArgs(TRUE)
out <- sub("^--out=", "", grep("^--out=", args, value = TRUE))
set.seed(7)
m <- matrix(rpois(12 * 40, 2), nrow = 12)
rownames(m) <- paste0("G", 1:12); colnames(m) <- paste0("cell", 1:40)
obj <- CreateSeuratObject(counts = m)
obj <- NormalizeData(obj)
obj <- FindVariableFeatures(obj)
obj <- ScaleData(obj)
obj <- RunPCA(obj, npcs = 5)
# run a command so @commands$time.stamp is populated
obj <- RunUMAP(obj, dims = 1:5)
saveRDS(obj, out)
'''


def t9_rds_fingerprint_stable(tmp):
    """Two Seurat objects built by the SAME code run twice (so their
    @commands$time.stamp necessarily differ) must yield IDENTICAL .rds
    fingerprints; and mutating one meta column must change the fingerprint.

    Falsifies: the @commands timestamp leaking into the fingerprint
    (a single object re-fingerprinted twice cannot catch this, because
    the timestamp is constant within one object — only two independent
    runs differ in it); and over-exclusion that would make a real
    content change invisible."""
    import h5py  # noqa (unused here, kept for symmetrical imports)
    maker = os.path.join(tmp, "make_two_rds.R")
    with open(maker, "w", encoding="utf-8") as fh:
        fh.write(RDS_MAKER_R)
    rds_a = os.path.join(tmp, "obj_a.rds")
    rds_b = os.path.join(tmp, "obj_b.rds")
    for rds in (rds_a, rds_b):
        p = subprocess.run([RSCRIPT, maker, "--out=" + rds],
                           capture_output=True, text=True, encoding="utf-8")
        if p.returncode != 0:
            record("T9 rds fingerprint stable across runs", False,
                   f"RDS maker failed: {p.stderr[-300:]}")
            return
    fa = subprocess.run([RSCRIPT, FP_R, "--file", rds_a],
                        capture_output=True, text=True, encoding="utf-8")
    fb = subprocess.run([RSCRIPT, FP_R, "--file", rds_b],
                        capture_output=True, text=True, encoding="utf-8")
    if fa.returncode != 0 or fb.returncode != 0:
        record("T9 rds fingerprint stable across runs", False,
               f"rds fingerprint failed:\n{fa.stderr[-300:]}\n{fb.stderr[-300:]}")
        return
    ja, jb = json.loads(fa.stdout), json.loads(fb.stdout)
    # the two objects live in files with different names; "file" is a
    # bookkeeping field, not fingerprint content — normalize it before
    # comparing so only REAL fingerprint content is tested.
    ja["file"], jb["file"] = "<same>", "<same>"
    stable_ok = equal_json(ja, jb)

    # reverse case: change one meta column value -> fingerprint must change
    # Paths are passed via commandArgs (not embedded in the R source) so
    # Windows backslashes in the temp path cannot be parsed as R escapes.
    mutate_r = r'''
suppressPackageStartupMessages(library(Seurat))
args <- commandArgs(TRUE)
src <- sub("^--src=", "", grep("^--src=", args, value = TRUE))
dst <- sub("^--dst=", "", grep("^--dst=", args, value = TRUE))
obj <- readRDS(src)
# mutate a counts-layer value so the rds fingerprint's assays.sum
# necessarily changes (meta.data columns are not fingerprinted beyond
# their names, so mutate content that IS in the fingerprint scope)
m <- GetAssayData(obj, assay = "RNA", layer = "counts")
m[1, 1] <- m[1, 1] + 1
obj <- SetAssayData(obj, assay = "RNA", layer = "counts", new.data = m)
saveRDS(obj, dst)
'''
    mutate_path = os.path.join(tmp, "mutate.R")
    rds_c = os.path.join(tmp, "obj_c.rds")
    with open(mutate_path, "w", encoding="utf-8") as fh:
        fh.write(mutate_r)
    pm = subprocess.run([RSCRIPT, mutate_path,
                         "--src=" + rds_a, "--dst=" + rds_c],
                        capture_output=True, text=True, encoding="utf-8")
    if pm.returncode == 0:
        fc = subprocess.run([RSCRIPT, FP_R, "--file", rds_c],
                            capture_output=True, text=True, encoding="utf-8")
        jc = json.loads(fc.stdout) if fc.returncode == 0 else {}
        if jc:
            jc["file"] = "<same>"
        changed_ok = not equal_json(ja, jc) if jc else False
    else:
        changed_ok = False
    record("T9 rds fingerprint stable across runs (timestamps) + counts-mutation sensitivity",
           stable_ok and changed_ok,
           "@commands timestamp leaking into the .rds fingerprint (two "
           "independent runs must be identical), OR over-exclusion hiding "
           "a real counts-layer change (a mutated value must be detected)")


def t10_h5_fingerprint_stable(tmp):
    """Two h5 files from the same fixture code must fingerprint
    identically, for BOTH the matrix and unknown layouts (补1)."""
    def make_h5(dest, layout):
        import scipy.sparse as sp
        d = os.path.join(tmp, "h5fix_" + layout)
        os.makedirs(d, exist_ok=True)
        rng = np.random.default_rng(123)
        genes, real, controls = mkfx.build_gene_names("human", 12)
        mat = sp.random(len(genes), 30, density=0.1, format="csc",
                        random_state=rng)
        mat.data = (rng.poisson(2, size=mat.data.shape) + 1).astype(np.int32)
        mat.eliminate_zeros()
        bc = mkfx.make_barcodes(rng, 30, "T")
        writer = mkfx.write_unknown_h5 if layout == "unknown" \
            else mkfx.write_10x_h5
        writer(os.path.join(d, "cell_feature_matrix.h5"), genes, bc, mat)
        return os.path.join(d, "cell_feature_matrix.h5")

    all_ok = True
    detail = []
    for layout in ("matrix", "unknown"):
        p_a = make_h5(tmp, layout)
        p_b = make_h5(tmp, layout)
        fa = fppy.fingerprint_h5(p_a)
        fb = fppy.fingerprint_h5(p_b)
        ok = equal_json(fa, fb) and fa["layout"] == layout
        detail.append(f"{layout}: {'same' if ok else 'DIFF'}")
        all_ok &= ok
    print("       " + "; ".join(detail))
    record("T10 h5 fingerprint stable across generations (matrix + unknown)",
           all_ok,
           "h5 fingerprint depending on HDF5 internal ordering, creation "
           "timestamps, or non-canonical layout-specific fields (two "
           "independent generations must be byte-deterministic in the "
           "fingerprint)")


def t11_fixture_dir_type_coverage(tmp):
    """Fingerprint a full fixture directory; assert every CSV's numeric
    columns are classified as 'numeric' (not degraded to 'text').

    Input independence: this test's input is make_fixture.py's output,
    NOT sample_rows()/CANONICAL_COLUMNS.  That is the only way to catch
    the regression where schema-declared typing left 30+ scientific CSVs
    (density_gene_correlations, cell_density, k_decision_table, ...) with
    all columns as text and 10/10 still green.
    """
    import scipy.sparse as sp
    fdir = os.path.join(tmp, "fixture")
    mkfx.main.__wrapped__ = None  # don't call main directly; replicate
    # minimal fixture: one matrix-layout h5 + cells.parquet + a CSV that
    # mirrors the real scientific CSVs (gene, rho, p, q, n_cells)
    rng = np.random.default_rng(999)
