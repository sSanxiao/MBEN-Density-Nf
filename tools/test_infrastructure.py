def _run_full_chain_for_sample(tmp, root, work, reg, sample, out_prefix):
    """Run R01->R02->R03->R04 single-sample chain for one sample,
    return dict of output dirs."""
    sub = sample.split("/")[1]
    dirs = {}
    prev = work
    for script, key in [
        ("R01_build_seurat.R", "r1"),
        ("R02_sctransform.R", "r2"),
        ("R03_density_gene_correlation.R", "r3"),
        ("R04_filter_density_genes.R", "r4"),
    ]:
        out = os.path.join(tmp, out_prefix + "_" + key)
        ok, _ = _run_r(os.path.join(root, "02_R_core_pipeline", script),
                       ["--sample", sample, "--registry", reg,
                        "--indir", prev, "--outdir", out], tmp, script)
        if not ok:
            return None
        dirs[key] = out
        prev = out
    return dirs


